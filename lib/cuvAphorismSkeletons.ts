function inferFrameLogic(frame: string): AphorismLogic {
  const warnsAgainstBehavior =
    /(?:不要|不可|莫要|休要|免得|离开|弃绝|止住)[^。；]{0,28}【行为】|不去【行为】|不可继续【行为】/u.test(
      frame,
    );
  const affirmsBehavior =
    /(?:当|要|务要|必须|应当|只管|宁可|肯|甘心|乐意|竭力|持守|坚守|追求)[^。；]{0,28}【行为】|【行为】[^。；]{0,36}(?:就当持守|当持守|不可丢弃|是有福的)/u.test(
      frame,
    );
  if (warnsAgainstBehavior && affirmsBehavior) return "contrast";
  if (warnsAgainstBehavior) return "warn";
  if (affirmsBehavior) return "affirm";
  return /(?:不是|乃是|却|反而|惟有|一边|另一边)/u.test(frame)
    ? "contrast"
    : "cause";
}

function inferOutcomeTone(frame: string): OutcomePolarity {
  const slot = frame.indexOf("【结果】");
  if (slot < 0) return "neutral";
  const prefix = frame.slice(Math.max(0, frame.lastIndexOf("；", slot) + 1), slot);
  if (/(?:不能|不至|难以|无法)[^，；。]{0,10}$/u.test(prefix)) return "positive";
  if (/免得[^，；。]{0,14}$/u.test(prefix)) return "negative";

  const positive = prefix.match(
    /有福|喜乐|尊荣|智慧|忠实|诚实|正直|公义|和睦|越照越明|察验|忍耐|持守|得胜|站立得住|丰裕|保护|扶起|善道|正道|亲爱|顾念|能使|好叫|可以/gu,
  )?.length ?? 0;
  const negative = prefix.match(
    /偏离|恶|祸|败坏|跌倒|懒惰|虚空|网罗|受害|灭亡|亏损|失去|减少|无所得|贫穷|穷乏|背道|疏忽|残忍|贪恋/gu,
  )?.length ?? 0;
  if (positive > negative) return "positive";
  if (negative > positive) return "negative";
  return "neutral";
}

