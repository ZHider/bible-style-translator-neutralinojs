function normalizeSubject(value: string) {
  return value
    .trim()
    .replace(/^凡/u, "")
    .replace(/^若/u, "")
    .replace(/^愿意(?=饶恕|帮助|分享|施舍|担当|陪伴)/u, "肯")
    .replace(/饶恕别人的过错/gu, "饶恕人的过犯")
    .replace(/的人$/u, "")
    .replace(/的$/u, "")
    .replace(/[，；。！？\s]+$/gu, "") || "如此行";
}

