function countTriggerWeight(pattern: RegExp, value: string) {
  if (pattern.source === "[\\s\\S]*") return 0;
  const flags = pattern.flags.includes("g") ? pattern.flags : `${pattern.flags}g`;
  const matcher = new RegExp(pattern.source, flags);
  return [...value.matchAll(matcher)].reduce(
    (total, match) => total + Math.max(1, match[0].length),
    0,
  );
}

function chooseTheme(category: string, result: string) {
  const source = `${category}，${result}`;
  const preferredThemeId =
    /(?:失败|跌倒|挫折|打击).{0,18}(?:前行|起来|继续|不放弃|耐心|忍耐)|(?:前行|起来|继续|不放弃|耐心|忍耐).{0,18}(?:失败|跌倒|挫折|打击)/u.test(
      category,
    )
      ? "adversity"
      : /忍耐|耐心|坚持|不放弃|熬过/u.test(category)
        ? "patience"
      : /认真(?:工作|做事)|每天工作|每日工作|作工|勤奋工作/u.test(category)
        ? "diligence"
      : /朋友|友情|伙伴|同伴|忠诚|义气|陪伴/u.test(category)
        ? "friendship"
        : /捷径|正路|歧路|偏路|道路|岔路/u.test(category)
          ? "way"
          : /怎样对待|怎么对待|待人|量给|回敬|以.{0,8}(?:恶意|善意|恩慈).{0,6}(?:待|对)/u.test(source)
            ? "measure"
            : /用.{0,8}恶意.{0,8}(?:待|对)|以.{0,8}善意.{0,8}(?:待|对)/u.test(source)
              ? "measure"
            : /种|收获|收割|自食其果|咎由自取|报应|代价/u.test(source)
              ? "sow-reap"
              : "";
  const preferred = APHORISM_THEMES.find((item) => item.id === preferredThemeId);
  if (preferred) return preferred;

  const scored = APHORISM_THEMES.slice(0, -1)
    .map((item, index) => ({
      item,
      index,
      score:
        countTriggerWeight(item.triggers, category) * 3 +
        countTriggerWeight(item.triggers, result),
    }))
    .filter((entry) => entry.score > 0)
    .sort((left, right) => right.score - left.score || left.index - right.index);
  return scored[0]?.item ?? APHORISM_THEMES.at(-1)!;
}

function frameSlotPenalty(frame: string, category: string) {
  let penalty = 0;
  const length = [...category].length;
  if (/在【行为】上|在【行为】中/u.test(frame)) penalty += length > 6 ? 8 : 3;
  if (/行【行为】|借【行为】|关于【行为】/u.test(frame)) penalty += 7;
  if (/【行为】的(?:工|时机|外貌)/u.test(frame)) penalty += 6;
  if (/论到【行为】|凡【行为】|人若【行为】|【行为】虽|【行为】若/u.test(frame)) {
    penalty -= 2;
  }
  if (/^【行为】/u.test(frame)) penalty -= 1;
  return penalty;
}

