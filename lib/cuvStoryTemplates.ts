const STORY_FALLBACK_IDS = [
  "call-journey",
  "trial-dialogue",
  "two-foundations",
] as const;

export function selectCuvStoryTemplates(source: string, limit = 4) {
  const priority = new Map(
    [
      "shipwreck",
      "two-claimants",
      "public-trial",
      "betrayal-meal",
      "entrusted-talents",
      "two-foundations",
      "neighbor-rescue",
      "lost-return",
      "giant-duel",
      "banquet-petition",
      "flood-warning",
    ].map((id, index) => [id, index]),
  );
  const matched = CUV_STORY_TEMPLATES.filter((item) => item.triggers.test(source)).sort(
    (left, right) =>
      (priority.get(left.id) ?? Number.MAX_SAFE_INTEGER) -
      (priority.get(right.id) ?? Number.MAX_SAFE_INTEGER),
  );
  const selected = [...matched];
  for (const id of STORY_FALLBACK_IDS) {
    const fallback = CUV_STORY_TEMPLATES.find((item) => item.id === id);
    if (fallback && !selected.includes(fallback)) selected.push(fallback);
  }
  return selected.slice(0, limit);
}

export function buildCuvStoryTemplatePrompt(source: string) {
  const selected = selectCuvStoryTemplates(source);
  return `本篇可以借用以下和合本故事编排原型。只借结构、节奏、比喻和冲突重心；所有人物、物品、场所、动作归属与实际结局仍来自输入：\n${selected
    .map(
      (item, index) =>
        `${index + 1}. ${item.sourceStory}\n   适用：${item.useWhen}\n   编排：${item.structure}\n   边界：${item.constraints}`,
    )
    .join("\n")}`;
}
